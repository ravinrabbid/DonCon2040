bool Crypto::setKey(std::span<uint8_t, KEY_DATA_LENGTH> key_data) {
    auto rand = key_data.subspan(0, RAND_LENGTH) | std::views::reverse;
    auto key = key_data.subspan(RAND_LENGTH, KEY_LENGTH) | std::views::reverse;

    const auto generateKey = [&](uint8_t idx) {
        const auto &expected = expected_answers.at(idx);

        std::array<uint8_t, RAND_LENGTH> transformed{};
        std::ranges::transform(rand, transformed.begin(), [](const auto &v) { return keytest_sbox.at(v); });

        return std::array<uint8_t, KEY_LENGTH>{
            static_cast<uint8_t>(
                transformed.at(7) ^
                (transformed.at(6) + std::rotl<uint8_t>(expected.at(0) ^ transformed.at(0), transformed.at(1)))),
            static_cast<uint8_t>(
                transformed.at(1) ^
                (transformed.at(3) + std::rotl<uint8_t>(expected.at(1) ^ transformed.at(4), transformed.at(2)))),
            static_cast<uint8_t>(
                transformed.at(5) ^
                (transformed.at(4) + std::rotl<uint8_t>(expected.at(2) ^ transformed.at(2), transformed.at(8)))),
            static_cast<uint8_t>(
                transformed.at(0) ^
                (transformed.at(7) + std::rotl<uint8_t>(expected.at(3) ^ transformed.at(6), transformed.at(9)))),
            static_cast<uint8_t>(
                transformed.at(1) ^
                (transformed.at(8) + std::rotl<uint8_t>(expected.at(4) ^ transformed.at(5), transformed.at(4)))),
            static_cast<uint8_t>(
                transformed.at(5) ^
                (transformed.at(8) + std::rotl<uint8_t>(expected.at(5) ^ transformed.at(9), transformed.at(3)))),
        };
    };

    const auto generateTables = [&](uint8_t idx) {
        const auto &sbox_a = sboxes.at(idx);
        const auto &sbox_b = sboxes.at(idx + 1);

        // NOLINTBEGIN(cppcoreguidelines-pro-bounds-avoid-unchecked-container-access)
        forward_table.at(0) = sbox_a.at(key[4]) ^ sbox_b.at(rand[3]);
        forward_table.at(1) = sbox_a.at(key[2]) ^ sbox_b.at(rand[5]);
        forward_table.at(2) = sbox_a.at(key[5]) ^ sbox_b.at(rand[7]);
        forward_table.at(3) = sbox_a.at(key[0]) ^ sbox_b.at(rand[2]);
        forward_table.at(4) = sbox_a.at(key[1]) ^ sbox_b.at(rand[4]);
        forward_table.at(5) = sbox_a.at(key[3]) ^ sbox_b.at(rand[9]);
        forward_table.at(6) = sbox_a.at(rand[0]) ^ sbox_b.at(rand[6]);
        forward_table.at(7) = sbox_a.at(rand[1]) ^ sbox_b.at(rand[8]);
        // NOLINTEND(cppcoreguidelines-pro-bounds-avoid-unchecked-container-access)

        // NOLINTBEGIN(cppcoreguidelines-pro-bounds-avoid-unchecked-container-access)
        sbox_indices.at(0) = sbox_a.at(key[0]) ^ sbox_b.at(rand[1]);
        sbox_indices.at(1) = sbox_a.at(key[5]) ^ sbox_b.at(rand[4]);
        sbox_indices.at(2) = sbox_a.at(key[3]) ^ sbox_b.at(rand[0]);
        sbox_indices.at(3) = sbox_a.at(key[2]) ^ sbox_b.at(rand[9]);
        sbox_indices.at(4) = sbox_a.at(key[4]) ^ sbox_b.at(rand[7]);
        sbox_indices.at(5) = sbox_a.at(key[1]) ^ sbox_b.at(rand[8]);
        sbox_indices.at(6) = sbox_a.at(rand[3]) ^ sbox_b.at(rand[5]);
        sbox_indices.at(7) = sbox_a.at(rand[2]) ^ sbox_b.at(rand[6]);
        // NOLINTEND(cppcoreguidelines-pro-bounds-avoid-unchecked-container-access)
    };

    for (size_t idx = 0; idx < sboxes.size() - 1; ++idx) {
        if (std::ranges::equal(generateKey(idx), key)) {
            generateTables(idx);
            return true;
        }
    }

    return false;
}

uint8_t Crypto::encrypt(uint8_t data, uint8_t address) {
    return (data - forward_table.at(address % 8)) ^ sbox_indices.at(address % 8);
}

uint8_t Crypto::decrypt(uint8_t data, uint8_t address) {
    return (data ^ sbox_indices.at(address % 8)) + forward_table.at(address % 8);
}

